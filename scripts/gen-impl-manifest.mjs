#!/usr/bin/env node
/**
 * 从 src/main/capabilities/ 生成两样东西：
 *   src/main/capabilities/index.ts        —— 能力汇总 + runCapability
 *   src/shared/implemented.generated.ts   —— 渲染层可用的 id 清单与摘要（不能 import electron）
 *
 * 新增一个能力 = 在目录里新建一个文件（导出 id / summary / run），然后 npm run impl:gen。
 *
 * 用法：
 *   node scripts/gen-impl-manifest.mjs           写入
 *   node scripts/gen-impl-manifest.mjs --check   只校验（CI / npm run check 用）
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = resolve(ROOT, 'src/main/capabilities')
/** 新轨：一个类一个文件，按层分目录。和 capabilities/ 并存，迁移完成后删旧轨。 */
const CLASSES_DIR = resolve(ROOT, 'src/main/classes')
const INDEX_PATH = join(DIR, 'index.ts')
const MANIFEST_PATH = resolve(ROOT, 'src/shared/implemented.generated.ts')

const HEADER = '// AUTO-GENERATED by scripts/gen-impl-manifest.mjs — 不要手改。\n'

/** 递归列出目录下所有 .ts（不含 _ 开头的私有文件） */
function walkTs(dir, prefix = '') {
  if (!existsSync(dir)) return []
  const out = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (name.startsWith('_')) continue
    if (name === 'index.ts') continue
    const rel = prefix ? `${prefix}/${name}` : name
    if (name.endsWith('.ts')) out.push(rel)
    else {
      try {
        // 目录
        if (readdirSync(full)) out.push(...walkTs(full, rel))
      } catch {
        /* 不是目录，忽略 */
      }
    }
  }
  return out.sort()
}

/**
 * 扫描新轨 src/main/classes/**：
 * 每个文件必须导出 classId + summary + run。
 *
 * 和旧轨的区别：旧轨用 `export const id`，新轨用 `export const classId`。
 * 两边都收，是因为迁移要分五步走，中间态必须能通过校验。
 */
export function scanClassImpls() {
  const files = walkTs(CLASSES_DIR)
  const modules = []
  const problems = []

  for (const file of files) {
    const source = readFileSync(join(CLASSES_DIR, file), 'utf8')
    const classId = source.match(/export const classId = '([^']+)'/)?.[1]
    const summary = source.match(/export const summary = '([^']+)'/)?.[1]
    if (!classId) {
      problems.push(`classes/${file}: 缺少 export const classId = '...'`)
      continue
    }
    if (!summary) problems.push(`classes/${file}: 缺少 export const summary = '...'`)
    if (!/export const run\b/.test(source) && !/export function run\b/.test(source)) {
      problems.push(`classes/${file}: 缺少 export const run`)
    }
    // classId 必须和所在层目录一致 —— 目录是 layout，classId 是语义，两者不能对不上
    const layerDir = file.split('/')[0]
    if (!classId.startsWith(`${layerDir}.`)) {
      problems.push(`classes/${file}: classId ${classId} 与所在层目录 ${layerDir}/ 不一致`)
    }
    modules.push({ file: `classes/${file}`, classId, summary: summary ?? '' })
  }

  const seen = new Map()
  for (const module of modules) {
    const previous = seen.get(module.classId)
    if (previous) problems.push(`classId 重复：${module.classId}（${previous} 与 ${module.file}）`)
    seen.set(module.classId, module.file)
  }
  return { files, modules, problems }
}

/** 扫描能力目录，并做格式与唯一性检查 */
export function scanCapabilities() {
  const files = readdirSync(DIR)
    .filter((name) => name.endsWith('.ts') && name !== 'index.ts' && !name.startsWith('_'))
    .sort()

  const modules = []
  const problems = []

  for (const file of files) {
    const source = readFileSync(join(DIR, file), 'utf8')
    const id = source.match(/export const id = '([^']+)'/)?.[1]
    const summary = source.match(/export const summary = '([^']+)'/)?.[1]
    if (!id) problems.push(`${file}: 缺少 export const id = '...'`)
    if (!summary) problems.push(`${file}: 缺少 export const summary = '...'`)
    if (!/export const run\b/.test(source)) problems.push(`${file}: 缺少 export const run`)
    if (id && summary) modules.push({ file, id, summary })
  }

  const seen = new Map()
  for (const module of modules) {
    const previous = seen.get(module.id)
    if (previous) problems.push(`id 重复：${module.id}（${previous} 与 ${module.file}）`)
    seen.set(module.id, module.file)
  }

  return { files, modules, problems }
}

export function renderIndex(modules) {
  const imports = modules
    .map((module, index) => `import * as cap${index} from './${module.file.replace(/\.ts$/, '')}'`)
    .join('\n')
  const list = modules.map((_, index) => `cap${index}`).join(',\n  ')

  return `${HEADER}// 新增能力：在 src/main/capabilities/ 新建一个文件（导出 id / summary / run），然后跑 npm run impl:gen。
import type { RunContext, RunOutcome } from '../layerStore'
import type { Capability } from './_shared'
${imports}

const MODULES = [
  ${list}
]

export const CAPABILITIES: Record<string, Capability> = Object.fromEntries(
  MODULES.map((module) => [module.id, module.run])
)

export async function runCapability(context: RunContext): Promise<RunOutcome | null> {
  const capability = CAPABILITIES[context.instance.classId]
  if (!capability) return null
  try {
    return await capability(context)
  } catch (error) {
    return {
      status: 'warn',
      output: \`执行异常：\${error instanceof Error ? error.message : String(error)}\`,
      elapsedMs: 0
    }
  }
}
`
}

export function renderManifest(modules) {
  const ids = modules.map((module) => `  '${module.id}'`).join(',\n')
  const summaries = modules.map((module) => `  '${module.id}': '${module.summary}'`).join(',\n')

  return `${HEADER}export const IMPLEMENTED_CLASS_IDS = [
${ids}
] as const

export const IMPL_SUMMARY: Record<(typeof IMPLEMENTED_CLASS_IDS)[number], string> = {
${summaries}
}
`
}

export function buildOutputs() {
  const legacy = scanCapabilities()
  const classes = scanClassImpls()

  // 双轨合并：同 id 时以新轨为主（迁移期间可能两边都有）
  const merged = new Map()
  for (const module of legacy.modules) merged.set(module.id, { id: module.id, summary: module.summary })
  for (const module of classes.modules) merged.set(module.classId, { id: module.classId, summary: module.summary })
  const all = [...merged.values()].sort((a, b) => a.id.localeCompare(b.id))

  return {
    problems: [...legacy.problems, ...classes.problems],
    index: renderIndex(legacy.modules),
    classIndex: renderClassIndex(classes.modules),
    manifest: renderManifest(all),
    modules: all,
    legacyCount: legacy.modules.length,
    classCount: classes.modules.length
  }
}

/**
 * 新轨注册表：classId → run。
 * 生成成一张表之后，各层 runner 就是纯分派，不再有 classId 分支。
 */
export function renderClassIndex(modules) {
  if (!modules.length) {
    return `${HEADER}// 新轨还没有实现单元。
// 新增：在 src/main/classes/<layer>/ 下新建文件，导出 classId / summary / run，然后 npm run impl:gen。
import type { ClassImpl } from '../../shared/classImpl'

export const CLASS_IMPLS: Record<string, ClassImpl> = {}
`
  }
  const imports = modules
    .map((module, index) => `import * as impl${index} from './${module.file.replace(/^classes\//, '').replace(/\.ts$/, '')}'`)
    .join('\n')
  const entries = modules.map((module, index) => `  ['${module.classId}', impl${index} as unknown as ClassImpl]`).join(',\n')
  return `${HEADER}import type { ClassImpl } from '../../shared/classImpl'
${imports}

/** classId → 实现单元。各层 runner 用它做纯分派。 */
export const CLASS_IMPLS: Record<string, ClassImpl> = Object.fromEntries([
${entries}
] as Array<[string, ClassImpl]>)
`
}

/** 返回漂移清单（空数组 = 生成物与能力目录一致） */
export function drift() {
  const { problems, index, manifest } = buildOutputs()
  const result = [...problems]
  const currentIndex = existsSync(INDEX_PATH) ? readFileSync(INDEX_PATH, 'utf8') : ''
  const currentManifest = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf8') : ''
  if (currentIndex !== index) result.push('src/main/capabilities/index.ts 与能力目录不一致')
  if (currentManifest !== manifest) result.push('src/shared/implemented.generated.ts 与能力目录不一致')
  return result
}

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
const CLASS_INDEX_PATH = resolve(ROOT, 'src/main/classes/index.ts')

if (isCli) {
  const { problems, index, manifest, classIndex, modules, legacyCount, classCount } = buildOutputs()
  if (problems.length) {
    console.error('能力目录有问题：')
    for (const problem of problems) console.error(`  · ${problem}`)
    process.exit(1)
  }
  if (process.argv.includes('--check')) {
    const issues = drift()
    if (issues.length) {
      console.error('能力清单未同步：')
      for (const issue of issues) console.error(`  · ${issue}`)
      console.error('\n跑一下：npm run impl:gen')
      process.exit(1)
    }
    console.log(`实现清单一致（共 ${modules.length} 个：旧轨 ${legacyCount} + 新轨 ${classCount}）`)
  } else {
    writeFileSync(INDEX_PATH, index, 'utf8')
    writeFileSync(MANIFEST_PATH, manifest, 'utf8')
    mkdirSync(dirname(CLASS_INDEX_PATH), { recursive: true })
    writeFileSync(CLASS_INDEX_PATH, classIndex, 'utf8')
    console.log(`已生成 classes/index.ts · capabilities/index.ts · implemented.generated.ts`)
    console.log(`实现单元共 ${modules.length} 个（旧轨 ${legacyCount} + 新轨 ${classCount}）`)
  }
}
