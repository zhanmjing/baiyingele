#!/usr/bin/env node
/**
 * 从 src/main/capabilities/ 生成两样东西：
 *   src/main/capabilities/index.ts        —— 能力汇总 + runCapability
 *   src/shared/implemented.generated.ts   —— 渲染层可用的 id 清单与摘要（不能 import electron）
 *
 * 新增一个能力 = 在目录里新建一个文件（导出 id / summary / run），然后 npm run impl:gen。
 *
 * 用法：
 *   node scripts/gen-impl-manifest.mjs           写入
 *   node scripts/gen-impl-manifest.mjs --check   只校验（CI / npm run check 用）
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DIR = resolve(ROOT, 'src/main/capabilities')
const INDEX_PATH = join(DIR, 'index.ts')
const MANIFEST_PATH = resolve(ROOT, 'src/shared/implemented.generated.ts')

const HEADER = '// AUTO-GENERATED by scripts/gen-impl-manifest.mjs — 不要手改。\n'

/** 扫描能力目录，并做格式与唯一性检查 */
export function scanCapabilities() {
  const files = readdirSync(DIR)
    .filter((name) => name.endsWith('.ts') && name !== 'index.ts' && !name.startsWith('_'))
    .sort()

  const modules = []
  const problems = []

  for (const file of files) {
    const source = readFileSync(join(DIR, file), 'utf8')
    const id = source.match(/export const id = '([^']+)'/)?.[1]
    const summary = source.match(/export const summary = '([^']+)'/)?.[1]
    if (!id) problems.push(`${file}: 缺少 export const id = '...'`)
    if (!summary) problems.push(`${file}: 缺少 export const summary = '...'`)
    if (!/export const run\b/.test(source)) problems.push(`${file}: 缺少 export const run`)
    if (id && summary) modules.push({ file, id, summary })
  }

  const seen = new Map()
  for (const module of modules) {
    const previous = seen.get(module.id)
    if (previous) problems.push(`id 重复：${module.id}（${previous} 与 ${module.file}）`)
    seen.set(module.id, module.file)
  }

  return { files, modules, problems }
}

export function renderIndex(modules) {
  const imports = modules
    .map((module, index) => `import * as cap${index} from './${module.file.replace(/\.ts$/, '')}'`)
    .join('\n')
  const list = modules.map((_, index) => `cap${index}`).join(',\n  ')

  return `${HEADER}// 新增能力：在 src/main/capabilities/ 新建一个文件（导出 id / summary / run），然后跑 npm run impl:gen。
import type { RunContext, RunOutcome } from '../layerStore'
import type { Capability } from './_shared'
${imports}

const MODULES = [
  ${list}
]

export const CAPABILITIES: Record<string, Capability> = Object.fromEntries(
  MODULES.map((module) => [module.id, module.run])
)

export async function runCapability(context: RunContext): Promise<RunOutcome | null> {
  const capability = CAPABILITIES[context.instance.classId]
  if (!capability) return null
  try {
    return await capability(context)
  } catch (error) {
    return {
      status: 'warn',
      output: \`执行异常：\${error instanceof Error ? error.message : String(error)}\`,
      elapsedMs: 0
    }
  }
}
`
}

export function renderManifest(modules) {
  const ids = modules.map((module) => `  '${module.id}'`).join(',\n')
  const summaries = modules.map((module) => `  '${module.id}': '${module.summary}'`).join(',\n')

  return `${HEADER}export const IMPLEMENTED_CLASS_IDS = [
${ids}
] as const

export const IMPL_SUMMARY: Record<(typeof IMPLEMENTED_CLASS_IDS)[number], string> = {
${summaries}
}
`
}

export function buildOutputs() {
  const { modules, problems } = scanCapabilities()
  return { problems, index: renderIndex(modules), manifest: renderManifest(modules), modules }
}

/** 返回漂移清单（空数组 = 生成物与能力目录一致） */
export function drift() {
  const { problems, index, manifest } = buildOutputs()
  const result = [...problems]
  const currentIndex = existsSync(INDEX_PATH) ? readFileSync(INDEX_PATH, 'utf8') : ''
  const currentManifest = existsSync(MANIFEST_PATH) ? readFileSync(MANIFEST_PATH, 'utf8') : ''
  if (currentIndex !== index) result.push('src/main/capabilities/index.ts 与能力目录不一致')
  if (currentManifest !== manifest) result.push('src/shared/implemented.generated.ts 与能力目录不一致')
  return result
}

const isCli = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isCli) {
  const { problems, index, manifest, modules } = buildOutputs()
  if (problems.length) {
    console.error('能力目录有问题：')
    for (const problem of problems) console.error(`  · ${problem}`)
    process.exit(1)
  }
  if (process.argv.includes('--check')) {
    const issues = drift()
    if (issues.length) {
      console.error('能力清单未同步：')
      for (const issue of issues) console.error(`  · ${issue}`)
      console.error('\n跑一下：npm run impl:gen')
      process.exit(1)
    }
    console.log(`能力清单一致（${modules.length} 个能力）`)
  } else {
    writeFileSync(INDEX_PATH, index, 'utf8')
    writeFileSync(MANIFEST_PATH, manifest, 'utf8')
    console.log(`已生成 index.ts 与 implemented.generated.ts（${modules.length} 个能力）`)
    for (const module of modules) console.log(`  ${module.id.padEnd(22)} ${module.summary}`)
  }
}
